#!/usr/bin/env python3
import os
import glob
import re

class CrashReporter:
    """
    Phân tích toàn bộ log trong logs/subagent/ và tổng hợp báo cáo Markdown:
    - Tính Delta RAM PSS
    - Bắt ngoại lệ FATAL EXCEPTION, OOM, ANR
    - Bóc tách Timber (FileName.kt:LineNumber)
    - Đếm instance Activity trong Backstack
    """

    def __init__(self, log_dir="logs/subagent", report_file="CRASH_REPORT_FINAL.md", package_id=None):
        self.log_dir = log_dir
        self.report_file = report_file
        self.package_id = package_id

    def extract_pss(self, file_path):
        if not os.path.exists(file_path):
            return 0
        with open(file_path, "r", errors="ignore") as f:
            for line in f:
                if "TOTAL PSS:" in line:
                    match = re.search(r"TOTAL PSS:\s+(\d+)", line)
                    if match:
                        return int(match.group(1)) // 1024
        return 0

    def generate_report(self):
        if not os.path.exists(self.log_dir):
            print(f"Log directory '{self.log_dir}' not found.")
            return

        before_files = sorted(glob.glob(os.path.join(self.log_dir, "*_mem_before.txt")))
        cases = []
        for bf in before_files:
            basename = os.path.basename(bf)
            case_id = basename.replace("_mem_before.txt", "")
            cases.append(case_id)

        if not cases:
            print("No test logs found to analyze.")
            return

        report_lines = [
            "# Crash Hunter 2.0 Comprehensive Stress & Diagnostic Report",
            "",
            "> **Generated by:** Antigravity Crash Hunter 2.0 (Dual-Engine)",
            f"> **Target Package:** `{self.package_id or 'Auto-Detected'}`",
            f"> **Total Cases Evaluated:** {len(cases)}",
            "",
            "## 1. Executive Summary Table",
            "",
            "| Case ID | Status | RAM Before | RAM After | RAM Delta | Fatal Crashes | Code Origin (File:Line) |",
            "|---------|--------|------------|-----------|-----------|---------------|-------------------------|"
        ]

        total_crashes = 0
        total_leaks = 0
        failures = 0
        detailed_errors = []

        for case in cases:
            before_file = os.path.join(self.log_dir, f"{case}_mem_before.txt")
            after_file = os.path.join(self.log_dir, f"{case}_mem_after.txt")
            filtered_file = os.path.join(self.log_dir, f"{case}_filtered.txt")
            backstack_file = os.path.join(self.log_dir, f"{case}_backstack.txt")

            ram_before = self.extract_pss(before_file)
            ram_after = self.extract_pss(after_file)
            ram_delta = ram_after - ram_before

            fatal_crashes = 0
            code_origin = "-"

            if os.path.exists(filtered_file):
                with open(filtered_file, "r", errors="ignore") as f:
                    content = f.read()
                    fatal_crashes = len(re.findall(r"FATAL EXCEPTION", content, re.IGNORECASE))
                    
                    # Bóc tách Timber_*: (FileName.kt:LineNumber)
                    timber_matches = re.findall(r"Timber_[a-zA-Z0-9_]+:\s*\(([a-zA-Z0-9_]+\.kt:\d+)\)", content)
                    if timber_matches:
                        code_origin = f"`{timber_matches[0]}`"

            backstack_count = 0
            if os.path.exists(backstack_file):
                with open(backstack_file, "r", errors="ignore") as f:
                    for line in f:
                        if "MainActivity" in line:
                            backstack_count += 1

            total_crashes += fatal_crashes
            if ram_delta > 100:
                total_leaks += 1

            status = "✅ PASS"
            if fatal_crashes > 0:
                status = "🔴 CRASH"
                failures += 1
            elif ram_delta > 100:
                status = "🟡 RAM LEAK"
                failures += 1
            elif backstack_count > 2:
                status = "🟡 NAV LEAK"
                failures += 1

            report_lines.append(
                f"| `{case}` | **{status}** | {ram_before} MB | {ram_after} MB | {ram_delta:+d} MB | {fatal_crashes} | {code_origin} |"
            )

            if fatal_crashes > 0:
                detailed_errors.append(f"### Case `{case}` Stacktrace:\n")
                if os.path.exists(filtered_file):
                    with open(filtered_file, "r", errors="ignore") as f:
                        snippets = [line for line in f if "FATAL" in line or "Exception" in line or "Error" in line][:20]
                        detailed_errors.append("```text\n" + "".join(snippets) + "\n```\n")

        report_lines.extend([
            "",
            "## 2. Statistical Vitals",
            f"- **Total Fatal Crashes:** {total_crashes}",
            f"- **Memory Leaks (>100MB PSS):** {total_leaks}",
            f"- **Overall Health:** {'✅ ZERO DEFECTS / PASS' if failures == 0 else f'⚠️ ISSUES DETECTED ({failures} cases flagged)'}",
            ""
        ])

        if detailed_errors:
            report_lines.append("## 3. Crash Details & Stacktraces")
            report_lines.extend(detailed_errors)

        with open(self.report_file, "w") as f:
            f.write("\n".join(report_lines) + "\n")

        print(f"[*] Báo cáo nghiệm thu đã xuất tại: {self.report_file}")

if __name__ == "__main__":
    reporter = CrashReporter()
    reporter.generate_report()
